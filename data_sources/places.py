def resolve_region(region: str) -> str:
    """把使用者輸入對應到範例地區；找不到時拋出 KeyError（不再默默退回臺南）。"""
    r = region.strip()
    r = _ALIASES.get(r, r)
    if r not in MOCK_REGIONS:
        raise KeyError(f"範例資料目前只有：{'、'.join(MOCK_REGIONS)}")
    return r

COLUMNS = ["name", "category", "lat", "lng", "rating", "reviews", "open_h", "close_h", "indoor"]


def get_places(region: str) -> tuple[pd.DataFrame, bool]:
    """回傳 (範例景點表, True)。"""
    key = resolve_region(region)
    df = pd.DataFrame(MOCK_REGIONS[key], columns=COLUMNS)
    prefix = "tn" if key.startswith("臺南") else "tp"
    df["place_id"] = [f"mock_{prefix}{i:03d}" for i in range(len(df))]
    return df, True
